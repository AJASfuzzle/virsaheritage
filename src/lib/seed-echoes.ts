export function getSeedPosts(): EchoPost[] {
  return RAW.map((s) => {
    const creator = SEED_CREATORS[s.author_key];
    const { media_url, author_key, is_seed: _is, ...rest } = s;
    return {
      ...rest,
      media_type: "image",
      media_signed: [{ url: media_url, type: "image", path: media_url }],
      author: {
        id: creator.id,
        full_name: creator.full_name,
        avatar_url: creator.avatar_url,
        username: creator.username,
      },
    } as EchoPost;
  });
}

export function getSeedPostById(id: string): EchoPost | null {
  return getSeedPosts().find((p) => p.id === id) ?? null;
}

export function getSeedCreatorById(userId: string): SeedCreator | null {
  return Object.values(SEED_CREATORS).find((c) => c.id === userId) ?? null;
}

export function getSeedPostsByCreator(userId: string): EchoPost[] {
  return getSeedPosts().filter((p) => p.author_id === userId);
}

export function getSeedLibraryEchoes(): EchoPost[] {
  return getSeedPosts().filter((p) => p.submitted_to_library);
}

export function getSeedByCategory(category: string): EchoPost[] {
  return getSeedPosts().filter(
    (p) => (p.category ?? "").toLowerCase() === category.toLowerCase()
  );
}

export function isSeedId(id: string): boolean {
  return id.startsWith("seed-");
}
